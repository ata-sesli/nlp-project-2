"""Upload the fine-tuned BERT model to the Hugging Face Hub with a model card.

The card is written from results.json, so the numbers on the Hub match the training run.

In Colab, after logging in (from huggingface_hub import notebook_login; notebook_login()):
    python bert/push_to_hub.py --model-dir /content/drive/MyDrive/NLP-2/bert_full/model \
        --results /content/drive/MyDrive/NLP-2/bert_full/results.json \
        --repo-id akifkulll/finance-pii-bert-base-cased
Add --dry-run to only write the model card without uploading.
Add --card-only to upload just the model card (README.md), e.g. after editing the card text.
"""

import argparse
import json
from pathlib import Path

TYPES = ["NAME", "COMPANY", "ADDRESS", "DATE", "EMAIL", "PHONE", "ACCOUNT", "ID"]


def model_card(r, repo_id):
    t, v = r["splits"]["test"], r["splits"]["val"]
    s = r["settings"]
    rows = "\n".join(
        f"| {k} | {t['per_type'][k]['precision']:.4f} | {t['per_type'][k]['recall']:.4f} | "
        f"{t['per_type'][k]['f1-score']:.4f} | {int(t['per_type'][k]['support'])} |"
        for k in TYPES if k in t["per_type"])
    return f"""---
license: apache-2.0
language: en
base_model: {s['model']}
datasets:
- gretelai/synthetic_pii_finance_multilingual
pipeline_tag: token-classification
tags:
- ner
- pii
- token-classification
---

# {repo_id.split('/')[-1]}

`{s['model']}` fine-tuned to find personal data (PII) in financial documents, as token
classification with BIO tags. 8 entity types (17 tags): NAME, COMPANY, ADDRESS, DATE, EMAIL,
PHONE, ACCOUNT, ID.

Built for the COE025 Natural Language Processing course project (İstinye University).
Code and data preparation: https://github.com/ata-sesli/nlp-project-2

## Use

```python
from transformers import pipeline

ner = pipeline("token-classification", model="{repo_id}",
               aggregation_strategy="first", stride=128)
ner("John Smith paid 500 EUR to XYZ Corp on 12 March 2024.")
```

`aggregation_strategy="first"` joins the subword pieces back into words and takes each word's tag
from its first piece, the same rule used in training. Each result is one entity:
`entity_group` (NAME, COMPANY, ...), `word`, `score` and the character offsets `start`, `end`.

`stride=128` lets texts longer than BERT's 512-token limit be read in overlapping windows, so
nothing is cut off. The model was trained on English synthetic financial documents.

## Training

- Data: English part of `gretelai/synthetic_pii_finance_multilingual`, cleaned and converted to
  word-level BIO by the project's `dataset/prepare_dataset.py`; {r['train_chunks']:,} training chunks
  of up to 200 words.
- {s['epochs']:g} epochs, learning rate {s['lr']}, {s['warmup']:.0%} linear warm-up, batch size
  {s['batch_size']}, fp16, seed {s['seed']}; best epoch chosen by validation entity F1.
- Labels go on the first subword of each word; chunks longer than {s['max_len']} subwords are split.
- Hardware: {r['gpu']}, {r['train_seconds'] / 60:.1f} minutes.

## Results (entity level, seqeval strict IOB2)

| Split | Precision | Recall | F1 | Missed PII |
|---|---:|---:|---:|---:|
| Validation | {v['precision']:.4f} | {v['recall']:.4f} | {v['f1']:.4f} | {v['missed_pii_rate']:.1%} |
| Test | {t['precision']:.4f} | {t['recall']:.4f} | {t['f1']:.4f} | {t['missed_pii_rate']:.1%} |

Test results per type:

| Type | Precision | Recall | F1 | Entities |
|---|---:|---:|---:|---:|
{rows}

## Limitations

The data is synthetic and English only, the labels were generated by the dataset authors, and the
model was trained once (one seed). Do not rely on it alone to protect real personal data.
"""


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--model-dir", required=True)
    p.add_argument("--results", required=True)
    p.add_argument("--repo-id", required=True)
    p.add_argument("--dry-run", action="store_true")
    p.add_argument("--card-only", action="store_true", help="upload only README.md, not the weights")
    a = p.parse_args()

    r = json.load(open(a.results))
    card = model_card(r, a.repo_id)
    Path(a.model_dir, "README.md").write_text(card, encoding="utf-8")
    print(card)
    if a.dry_run:
        return

    from huggingface_hub import HfApi
    api = HfApi()
    if a.card_only:
        api.upload_file(path_or_fileobj=str(Path(a.model_dir, "README.md")), path_in_repo="README.md",
                        repo_id=a.repo_id, commit_message="Update model card")
        print(f"model card updated -> https://huggingface.co/{a.repo_id}")
        return
    api.create_repo(a.repo_id, exist_ok=True)
    api.upload_folder(folder_path=a.model_dir, repo_id=a.repo_id,
                      commit_message="Upload fine-tuned BERT for financial PII NER")
    print(f"uploaded -> https://huggingface.co/{a.repo_id}")


if __name__ == "__main__":
    main()
